int fib(int n) { return n < 2 ? n : fib(n - 1) + fib(n - 2); }

// A string table and a function pointer in writable data: the module
// initializer stores their addresses.
const char *messages[] = {"fib(0) .. fib(20):", "sum & 0xff:"};
int (*fib_fn)(int) = fib;

static void print_int(int v) {
  char buf[12];
  char *p = buf + sizeof buf - 1;
  *p = '\0';
  do {
    *--p = (char)('0' + v % 10);
    v /= 10;
  } while (v != 0);
  puts(p);
}

// CHECK:      {{^}}.method public static int32 'main'() cil managed{{$}}
// CHECK:      {{^}}  localloc{{$}}
// CHECK:      {{^}}  ldsfld native int 'messages'{{$}}
// CHECK-NEXT: {{^}}  ldind.i{{$}}
// CHECK-NEXT: {{^}}  call int32 'puts'(native int){{$}}
// CHECK:      {{^}}  ldsfld native int 'fib_fn'{{$}}
// CHECK-NEXT: {{^}}  ldind.i{{$}}
// CHECK:      {{^}}  calli int32(int32){{$}}
// CHECK:      {{^}}} // end of method 'main'{{$}}
int main(void) {
  int sum = 0;
  puts(messages[0]);
  for (int i = 0; i <= 20; i++) {
    int f = fib_fn(i);
    print_int(f);
    sum += f;
  }
  puts(messages[1]);
  print_int(sum & 0xff);
  return sum & 0xff;
}

