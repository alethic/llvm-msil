// Design.md section 12, 'fib.c runs on dotnet', with its literal command line:
//   clang --target=x86_64-unknown-linux-gnu-msil -O2 -ffreestanding -S prog.c -o prog.il
// then 'ilasm -dll prog.il' (here %ilasm-verify, which adds -pe64 -x64,
// plan decision D31), and 'dotnet prog.dll' (run by the execution suite, see
// below). The program below is fib plus everything else Design.md 12 puts in
// scope for milestone 1, so the module has the complete skeleton of plan 5.1:
// the header and assembly declarations, methods with the C signatures, a static
// frame (localloc; at -O2 the buffer of the inlined print_int, at -O0 the
// locals), a function pointer used with ldftn + calli, one hard-coded P/Invoke
// 'puts -> DllImport("libc")' on Linux (D14), the data segment with a string
// table and the function pointer (D12), the module initializer that fills in
// their addresses (relocations; the function's address field of plan section
// 12, 'Phase-1 function addresses'), and the generated entry point that calls
// main() (D27).
//
// The skeleton is the same at -O2 (the literal command) and at -O0, which
// Design.md 12's exit criteria also require: clang reports nothing, and the
// data segment, module initializer and entry point are pinned exactly; method
// bodies are only checked for the instructions that make up the skeleton.
// The module is assembled with ilasm when the test suite provides the 'ilasm'
// feature and %ilasm-verify (as llvm/test/CodeGen/MSIL does). Running it
// prints fib(0) to fib(20), one per line, between the two messages, then 46
// (the sum of those numbers, 17710, masked to 8 bits, D37), and exits with
// 46; msil/test/M1/11-programs/fib.c runs fib at -O0 and -O2 against native
// clang on every runtime leg.

