int reload(int *p) {
  int a = *p;
  __asm__ volatile("" ::: "memory");
  return a + *p;
}

// The value loaded before the barrier waits in a local; *p is loaded again
// after it.
// EXACT-LABEL: .method {{.*}}'reload'(
// EXACT:       {{^}}  ldind.i4{{$}}
// EXACT-NEXT:  {{^}}  stloc.0{{$}}
// EXACT-NEXT:  {{^[[:blank:]]+//MEMBARRIER$}}
// EXACT:       {{^}}  ldind.i4{{$}}
// EXACT:       {{^}}  add{{$}}
