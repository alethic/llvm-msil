// A compiler barrier, 'asm volatile("" ::: "memory")', between two stores
// compiles for the MSIL triples (ImplementationPlan.md decision D36, M7.a,
// M7.c; plan section 12, row 'M1.d amended'): CodeGen turns the empty asm
// statement into 'fence syncscope("singlethread") seq_cst' plus a call to
// llvm.sideeffect, and the backend selects the fence as the generic
// MEMBARRIER pseudo, which emits only a comment line between the two stind.i4,
// keeps both stores, and does not let a load move across it. The line is one
// tab followed by '//MEMBARRIER', with no space after '//' (plan section 12,
// row 'Plan 5.1, D36, M7.a and M7.c amended (MEMBARRIER text)'): the EXACT and
// O0 lines reject '// MEMBARRIER' (FileCheck turns the tab into one space), and
// the TAB run, with --strict-whitespace, checks that all three barrier lines
// start with the tab and that no other line names MEMBARRIER.
// __atomic_signal_fence is the same compiler barrier, and
// __atomic_thread_fence(__ATOMIC_SEQ_CST) is a full barrier,
// 'call void [mscorlib]System.Threading.Interlocked::MemoryBarrier()'.
// 'clang --target=x86_64-pc-windows-msvc-msil -O2 -S' (the Design.md 12
// command line, without -ffreestanding, which these functions do not need)
// succeeds without a diagnostic, on Linux as well, and at -O0, where every
// parameter is spilled to the static frame (M7).
//
// This test does not assemble its output:
// llvm/test/CodeGen/MSIL/fence.ll runs llc and ilasm on a copy of the IR that
// clang emits for barrier() here (function 'asm_barrier_clang'), and
// msil/test/M1/05-memory/barrier.c assembles and runs C code of this kind.

