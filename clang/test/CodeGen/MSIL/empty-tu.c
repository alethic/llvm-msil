// An empty C translation unit compiled with 'clang -S' for an MSIL triple is a
// complete ILAsm module made of exactly the header of ImplementationPlan.md
// 5.1: the source file and the triple as comments, the mscorlib reference
// (decision D10) and the assembly named after the source-file stem (decision
// D28), with no GNU directive, no '.ident' and, on Windows, no CodeView
// section for the NoDebug compile unit clang emits there. clang passes native
// CPU and feature strings for the native ABI, which the MSIL target accepts
// without a 'not a recognized processor/feature' warning (decision D7).
// -faddrsig asks for an address-significance table ('.addrsig'), which the
// TargetMachine turns off (decision D8). The MinGW driver also passes
// -exception-model=seh even for C; an empty file shows no effect of the
// exception model, so the MinGW run only pins the header for that triple, and
// the D8 overrides themselves are pinned by
// llvm/unittests/Target/MSIL/MSILTargetMachineTest.cpp and
// llvm/test/CodeGen/MSIL/pipeline.ll.
//
// This test does not assemble its output:
// llvm/test/CodeGen/MSIL/empty-module.ll runs llc and ilasm on copies of the
// IR that clang emits for an empty file on x86_64-pc-windows-msvc19.33.0-msil
// (the versioned triple clang uses), x86_64-unknown-linux-gnu-msil and
// x86_64-w64-windows-gnu-msil; those copies must follow changes to that IR.

