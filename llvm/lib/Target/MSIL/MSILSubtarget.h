#ifndef LLVM_LIB_TARGET_MSIL_MSILSUBTARGET_H
#define LLVM_LIB_TARGET_MSIL_MSILSUBTARGET_H

#include "MCTargetDesc/MSILMCTargetDesc.h"
#include "MSILFrameLowering.h"
#include "MSILISelLowering.h"
#include "MSILInstrInfo.h"
#include "MSILSelectionDAGInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "MSILGenSubtargetInfo.inc"

namespace llvm {

class MSILSubtarget final : public MSILGenSubtargetInfo {
  /// The CPU and feature strings exactly as the front end wrote them (for
  /// example "x86-64" and "+cmov,+cx8,+sse2"). The MC subtarget is always the
  /// "generic" MSIL processor without features; these strings are kept for a
  /// later mapping of native SIMD features.
  std::string NativeCPU;
  std::string NativeFS;

  MSILFrameLowering FrameLowering;
  MSILInstrInfo InstrInfo;
  MSILSelectionDAGInfo TSInfo;
  MSILTargetLowering TLInfo;

  MSILSubtarget &initializeSubtargetDependencies();

public:
  /// This constructor initializes the data members to match that of the
  /// specified triple. \p CPU, \p TuneCPU and \p FS are the native strings.
  MSILSubtarget(const Triple &TT, StringRef CPU, StringRef TuneCPU,
                StringRef FS, const TargetMachine &TM);
  ~MSILSubtarget() override;

  const MSILSelectionDAGInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }
  const MSILFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const MSILTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const MSILInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const MSILRegisterInfo *getRegisterInfo() const override {
    return &getInstrInfo()->getRegisterInfo();
  }

  StringRef getNativeCPU() const { return NativeCPU; }
  StringRef getNativeFeatures() const { return NativeFS; }

  bool enableIndirectBrExpand() const override { return true; }
  bool useAA() const override { return true; }

  void initLibcallLoweringInfo(LibcallLoweringInfo &Info) const override;

  /// Parses features string setting specified subtarget options. Definition of
  /// function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);
};

} // end namespace llvm

#endif
