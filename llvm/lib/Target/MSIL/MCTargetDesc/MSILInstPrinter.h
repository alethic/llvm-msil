/// \file
/// This class prints an MSIL MCInst as ILAsm text: one CIL instruction per
/// line with a two-space indent. Every MCInst is a CIL_ record
/// (MSILInstrCIL.td), whose mnemonic is the CIL mnemonic and whose only
/// operand is the inline operand, so printing is table-driven; MSILMCInstLower
/// has chosen every form (ldarg.0, ldloc.s 4, ldc.i4.m1, br.s, ...) already.
///
/// The InstPrinter option object-form (llc -M object-form) prints token
/// operands in object form (MSILMemberRefExpr::printOperand), the text of a
/// CIL object (plan 5.8.4).
///
//===----------------------------------------------------------------------===//

#ifndef LLVM_LIB_TARGET_MSIL_MCTARGETDESC_MSILINSTPRINTER_H
#define LLVM_LIB_TARGET_MSIL_MCTARGETDESC_MSILINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"
#include <cstdint>
#include <utility>

namespace llvm {

class MCSubtargetInfo;

class MSILInstPrinter final : public MCInstPrinter {
  /// Print token operands in object form (the option object-form).
  bool ObjectForm = false;

public:
  MSILInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                  const MCRegisterInfo &MRI);

  /// Accepts "object-form".
  bool applyTargetSpecificCLOption(StringRef Opt) override;

  void printRegName(raw_ostream &OS, MCRegister Reg) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &OS) override;

  // Used by tblgen code (the PrintMethods of MSILInstrInfo.td).

  /// Integer immediates in decimal, labels through MCAsmInfo::printExpr.
  void printOperand(const MCInst *MI, unsigned OpNo, const MCSubtargetInfo &STI,
                    raw_ostream &O);
  /// A CIL local index (ldloc.s, stloc, ldloca, ...), in decimal.
  void printLocalOperand(const MCInst *MI, unsigned OpNo,
                         const MCSubtargetInfo &STI, raw_ostream &O);
  /// A CIL argument index (ldarg.s, starg, ldarga, ...), in decimal.
  void printArgOperand(const MCInst *MI, unsigned OpNo,
                       const MCSubtargetInfo &STI, raw_ostream &O);
  /// The bit pattern of a float32 immediate: float32(0x7FC00000).
  void printF32ImmOperand(const MCInst *MI, unsigned OpNo,
                          const MCSubtargetInfo &STI, raw_ostream &O);
  /// The bit pattern of a float64 immediate: float64(0x3FF8000000000000).
  void printF64ImmOperand(const MCInst *MI, unsigned OpNo,
                          const MCSubtargetInfo &STI, raw_ostream &O);
  /// A metadata token: an MSILMemberRefExpr in whole-program or object form,
  /// or an immediate holding a final token, as ILAsm's 'mdtoken(0x...)'.
  void printTokenOperand(const MCInst *MI, unsigned OpNo,
                         const MCSubtargetInfo &STI, raw_ostream &O);

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address,
                        const MCSubtargetInfo &STI, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

private:
  /// 'switch (<targets>)': the operands of CIL_Switch, one label (or
  /// displacement from the end of the switch) per target.
  void printSwitch(const MCInst *MI, const MCSubtargetInfo &STI,
                   raw_ostream &O);
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_MSIL_MCTARGETDESC_MSILINSTPRINTER_H
