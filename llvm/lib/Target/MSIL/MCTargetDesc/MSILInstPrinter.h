/// \file
/// This class prints an MSIL MCInst as ILAsm text: one CIL opcode per line
/// with a two-space indent. Opcodes that take an argument index, a local index
/// or an integer constant are printed in their shortest form (ldarg.0,
/// ldloc.s 4, ldc.i4.m1, ...); branches always in their long form (br @BB0_2,
/// brtrue @BB0_2, blt.un @BB0_2, ...), and a switch as its whole target list
/// followed by a 'br' to its first target, a dummy fall-through that never
/// runs (not the C switch's default).
///
/// MCInsts keep the operand positions of the MachineInstr: register operands
/// are placeholders for values on the evaluation stack and print nothing, so
/// asm strings name only immediate and symbol operands.
///
//===----------------------------------------------------------------------===//

#ifndef LLVM_LIB_TARGET_MSIL_MCTARGETDESC_MSILINSTPRINTER_H
#define LLVM_LIB_TARGET_MSIL_MCTARGETDESC_MSILINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"
#include <cstdint>
#include <utility>

namespace llvm {

class MCSubtargetInfo;

class MSILInstPrinter final : public MCInstPrinter {
public:
  MSILInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                  const MCRegisterInfo &MRI);

  void printRegName(raw_ostream &OS, MCRegister Reg) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &OS) override;

  // Used by tblgen code (the PrintMethods of MSILInstrInfo.td).

  /// Integer immediates in decimal, expressions (basic-block labels and
  /// MSILMemberRefExprs) through MCAsmInfo::printExpr, nothing for registers.
  void printOperand(const MCInst *MI, unsigned OpNo, const MCSubtargetInfo &STI,
                    raw_ostream &O);
  /// A CIL local index (ldloc, stloc). printInst prints the local opcodes in
  /// their short forms itself, so the generated printer never reaches this.
  void printLocalOperand(const MCInst *MI, unsigned OpNo,
                         const MCSubtargetInfo &STI, raw_ostream &O);
  /// A CIL argument index (ldarg, starg); as printLocalOperand.
  void printArgOperand(const MCInst *MI, unsigned OpNo,
                       const MCSubtargetInfo &STI, raw_ostream &O);
  /// The bit pattern of a float32 immediate: float32(0x7FC00000).
  void printF32ImmOperand(const MCInst *MI, unsigned OpNo,
                          const MCSubtargetInfo &STI, raw_ostream &O);
  /// The bit pattern of a float64 immediate: float64(0x3FF8000000000000).
  void printF64ImmOperand(const MCInst *MI, unsigned OpNo,
                          const MCSubtargetInfo &STI, raw_ostream &O);
  /// The 'unaligned. N' and 'volatile.' prefixes of a memflags immediate
  /// (MSIL::MemFlags), each as a line of its own followed by the indent of the
  /// next line, and nothing for 0. The operand therefore goes first in the asm
  /// string, before the opcode: "${flags}ldind.i4".
  void printMemFlagsOperand(const MCInst *MI, unsigned OpNo,
                            const MCSubtargetInfo &STI, raw_ostream &O);

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address,
                        const MCSubtargetInfo &STI, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

private:
  /// 'switch (<targets>)' then, on the next line, 'br <first target>'
  /// (BR_TABLE_I32: the int32 index placeholder, the jump-table block labels,
  /// then the first label again). That 'br' is a dummy fall-through target
  /// that is already a CFG successor and never runs: LLVM's range check before
  /// the table sends every out-of-range value to the default first. It is not
  /// the C switch's default.
  void printBrTable(const MCInst *MI, const MCSubtargetInfo &STI,
                    raw_ostream &O);
  /// 'call <method reference>' (CALL) or 'calli <call-site signature>'
  /// (CALL_INDIRECT, 'calli int32(native int, int32)' for a managed call):
  /// the one MSILMemberRefExpr operand among the register placeholders of the
  /// results, the arguments and, for calli, the callee address.
  void printCall(const MCInst *MI, const MCSubtargetInfo &STI, raw_ostream &O);
  /// Checks that the operand of GLOBAL_ADDR and FUNC_ADDR is an address field
  /// (an MSILMemberRefExpr from MSILMCInstLower): a global's, or a
  /// function's, which has no offset.
  void checkAddressOperand(const MCInst *MI);
  /// The 'ldc.i4 <offset>; add' (or 'ldc.i8 <offset>; conv.i; add') after the
  /// 'ldsfld' of a GLOBAL_ADDR whose operand has a non-zero offset.
  void printGlobalAddrOffset(const MCInst *MI, raw_ostream &O);
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_MSIL_MCTARGETDESC_MSILINSTPRINTER_H
