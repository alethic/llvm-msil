"""Generates a draft CILOpcodes.def X-macro (for llvm/include/llvm/BinaryFormat)
from the verified table in cilopcodes.py plus the stack behaviour and flow
control of System.Reflection.Emit.OpCodes (dotnet-opcodes.tsv).
Usage: gen_opcodes_def.py <dotnet-opcodes.tsv> <out.def>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cilopcodes as K  # noqa: E402

emit, ilop = {}, {}
for line in open(sys.argv[1], encoding="utf-8"):
    f = line.rstrip("\n").split("\t")
    if f[0] == "ILOpCode":
        ilop[int(f[2], 16)] = f[1]
    else:
        emit[f[0]] = f
out = [
    "//===- CILOpcodes.def - ECMA-335 Partition III opcodes ----------*- C++ -*-===//",
    "//",
    "// DRAFT generated by gen_opcodes_def.py (recon p2/metadata-writer). Values and",
    "// operand kinds: ECMA-335 6th edition, Partition III; checked against",
    "// System.Reflection.Emit.OpCodes, System.Reflection.Metadata.ILOpCode and the",
    "// bytes both ilasms assemble (check_opcodes.py). Pop/Push/Flow are the",
    "// StackBehaviour and FlowControl values of System.Reflection.Emit.OpCodes.",
    "//",
    "// CIL_OPCODE(Enum, Text, Value, Operand, Pop, Push, Flow)",
    "//   Value: 0x00XX one-byte opcode, 0xFEXX two-byte opcode.",
    "//",
    "//===----------------------------------------------------------------------===//",
    "",
    "#ifndef CIL_OPCODE",
    "#error \"define CIL_OPCODE before including CILOpcodes.def\"",
    "#endif",
    "",
]
for n, v, k in K.OPCODES:
    if n in emit:
        e = emit[n]
        pop, push, flow = e[4], e[5], e[6]
        enum = ilop[v]
    else:  # no. (ECMA only)
        pop, push, flow, enum = "Pop0", "Push0", "Meta", "No"
    enum = enum[0].upper() + enum[1:]
    out.append('CIL_OPCODE(%s, "%s", 0x%04X, %s, %s, %s, %s)' % (enum, n, v, k, pop, push, flow))
out += ["", "#undef CIL_OPCODE", ""]
open(sys.argv[2], "w", newline="\n").write("\n".join(out))
print(len(K.OPCODES), "opcodes written")
