"""Generates a draft CLITables.def X-macro (for llvm/include/llvm/BinaryFormat)
from the schema in cliwriter.py, which verify_schema.py checked against
System.Reflection.Metadata on .NET 8 and .NET Framework assemblies.
Usage: gen_tables_def.py <out.def>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cliwriter import SCHEMA, CODED, T, SORTED_KEYS  # noqa: E402

NAMES = {
    "Module": ["Generation", "Name", "Mvid", "EncId", "EncBaseId"],
    "TypeRef": ["ResolutionScope", "TypeName", "TypeNamespace"],
    "TypeDef": ["Flags", "TypeName", "TypeNamespace", "Extends", "FieldList", "MethodList"],
    "FieldPtr": ["Field"], "Field": ["Flags", "Name", "Signature"], "MethodPtr": ["Method"],
    "MethodDef": ["RVA", "ImplFlags", "Flags", "Name", "Signature", "ParamList"],
    "ParamPtr": ["Param"], "Param": ["Flags", "Sequence", "Name"],
    "InterfaceImpl": ["Class", "Interface"], "MemberRef": ["Class", "Name", "Signature"],
    "Constant": ["Type", "Parent", "Value"], "CustomAttribute": ["Parent", "Type", "Value"],
    "FieldMarshal": ["Parent", "NativeType"], "DeclSecurity": ["Action", "Parent", "PermissionSet"],
    "ClassLayout": ["PackingSize", "ClassSize", "Parent"], "FieldLayout": ["Offset", "Field"],
    "StandAloneSig": ["Signature"], "EventMap": ["Parent", "EventList"], "EventPtr": ["Event"],
    "Event": ["EventFlags", "Name", "EventType"], "PropertyMap": ["Parent", "PropertyList"],
    "PropertyPtr": ["Property"], "Property": ["Flags", "Name", "Type"],
    "MethodSemantics": ["Semantics", "Method", "Association"],
    "MethodImpl": ["Class", "MethodBody", "MethodDeclaration"], "ModuleRef": ["Name"],
    "TypeSpec": ["Signature"], "ImplMap": ["MappingFlags", "MemberForwarded", "ImportName", "ImportScope"],
    "FieldRVA": ["RVA", "Field"], "ENCLog": ["Token", "FuncCode"], "ENCMap": ["Token"],
    "Assembly": ["HashAlgId", "MajorVersion", "MinorVersion", "BuildNumber", "RevisionNumber", "Flags",
                 "PublicKey", "Name", "Culture"],
    "AssemblyProcessor": ["Processor"], "AssemblyOS": ["OSPlatformID", "OSMajorVersion", "OSMinorVersion"],
    "AssemblyRef": ["MajorVersion", "MinorVersion", "BuildNumber", "RevisionNumber", "Flags",
                    "PublicKeyOrToken", "Name", "Culture", "HashValue"],
    "AssemblyRefProcessor": ["Processor", "AssemblyRef"],
    "AssemblyRefOS": ["OSPlatformID", "OSMajorVersion", "OSMinorVersion", "AssemblyRef"],
    "File": ["Flags", "Name", "HashValue"],
    "ExportedType": ["Flags", "TypeDefId", "TypeName", "TypeNamespace", "Implementation"],
    "ManifestResource": ["Offset", "Flags", "Name", "Implementation"],
    "NestedClass": ["NestedClass", "EnclosingClass"],
    "GenericParam": ["Number", "Flags", "Owner", "Name"], "MethodSpec": ["Method", "Instantiation"],
    "GenericParamConstraint": ["Owner", "Constraint"],
}


def kind(k):
    if k == 2:
        return "U16", "None"
    if k == 4:
        return "U32", "None"
    if k == "S":
        return "StringIdx", "None"
    if k == "G":
        return "GuidIdx", "None"
    if k == "B":
        return "BlobIdx", "None"
    if k[0] == "T":
        return "TableIdx", k[1]
    return "CodedIdx", k[1]


out = [
    "//===- CLITables.def - ECMA-335 Partition II metadata tables ----*- C++ -*-===//",
    "//",
    "// DRAFT generated by gen_tables_def.py (recon p2/metadata-writer) from the",
    "// ECMA-335 II.22 schema that verify_schema.py checked against",
    "// System.Reflection.Metadata row sizes (34 of 45 tables seen in real",
    "// assemblies; the Ptr, ENC and Assembly(Ref)Processor/OS tables are never",
    "// emitted by current compilers but a reader must size them).",
    "//",
    "// CLI_TABLE(Id, Name, Sorted)        Sorted: II.22 requires a sort order",
    "// CLI_COLUMN(Table, Column, Kind, Target)",
    "//   Kind: U16, U32 (Constant.Type is one byte plus a padding byte: U16),",
    "//   StringIdx, GuidIdx, BlobIdx, TableIdx (Target = table), CodedIdx",
    "//   (Target = coded index kind).",
    "// CLI_CODED_INDEX(Name, TagBits, Tables...)  (None = unused tag)",
    "//",
    "//===----------------------------------------------------------------------===//",
    "",
    "#ifdef CLI_TABLE",
]
for name, tid in sorted(T.items(), key=lambda kv: kv[1]):
    out.append("CLI_TABLE(0x%02X, %s, %d)" % (tid, name, 1 if name in SORTED_KEYS else 0))
out += ["#undef CLI_TABLE", "#endif", "", "#ifdef CLI_COLUMN"]
for name, tid in sorted(T.items(), key=lambda kv: kv[1]):
    for col, k in zip(NAMES[name], SCHEMA[name]):
        kk, tgt = kind(k)
        out.append("CLI_COLUMN(%s, %s, %s, %s)" % (name, col, kk, tgt))
out += ["#undef CLI_COLUMN", "#endif", "", "#ifdef CLI_CODED_INDEX"]
for c, (bits, ts) in CODED.items():
    out.append("CLI_CODED_INDEX(%s, %d, %s)" % (c, bits, ", ".join(t or "None" for t in ts)))
out += ["#undef CLI_CODED_INDEX", "#endif", ""]
open(sys.argv[1], "w", newline="\n").write("\n".join(out))
print("written", sys.argv[1])
